    fun morningQuestionForToday(): String {
        val day = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)
        return morningPool[day % morningPool.size]
    }

    fun eveningQuestionForToday(): String {
        val day = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)
        return eveningPool[day % eveningPool.size]
    }

    fun levelUpQuestion(level: Int): String {
        val idx = (level - 1).coerceAtLeast(0) % levelUpPool.size
        return levelUpPool[idx]
    }

